"""Builds the synthetic profile shown on the website and runs Caladrius on it.

Every number the page prints about this profile comes from Caladrius: `model.simulate` makes the
noise-free curve, a fixed-seed proportional noise turns it into "observations" (rounded to three
significant digits), and `nca.run` analyses them with the default conventions. The page only rounds
for display.

Usage, from this folder: python3 make_specimen.py /path/to/caladrius-cli
It rewrites profile.csv here and ../src/specimen.json.
"""
import json
import math
import random
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLI = sys.argv[1] if len(sys.argv) > 1 else "caladrius-cli"

MODEL = "pk1.oral_1"
DOSE_MG = 200
PARAMS = {"ka": 1.1, "k": 0.115, "v": 32}  # 1/h, 1/h, L
TIMES_H = [0, 0.25, 0.5, 1, 1.5, 2, 3, 4, 6, 8, 12, 16, 24]
NOISE_CV = 0.06
SEED = 20261019
UNITS = {"time": "h", "concentration": "mg/L", "dose": "mg"}
SHOWN = ["cmax", "tmax", "auclast", "aucinf.obs", "aucpext.obs", "lambda.z", "half.life",
         "adj.r.squared", "cl.obs", "vz.obs", "mrt.obs"]


def run(args):
    out = subprocess.run([CLI, *args], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def sig(x, digits=3):
    if x == 0:
        return 0.0
    return round(x, digits - 1 - int(math.floor(math.log10(abs(x)))))


simulate = ["model.simulate", "--param", f"model={MODEL}", "--param", f"dose={DOSE_MG}",
            "--param", "params=" + json.dumps(PARAMS), "--param", "times=" + json.dumps(TIMES_H)]
sim = run(simulate)
rng = random.Random(SEED)
conc = [sig(c * math.exp(rng.gauss(0, NOISE_CV))) for c in sim["conc"]]

csv = "Time (h),Conc (mg/L),Dose (mg)\n" + "".join(f"{t},{c},{DOSE_MG}\n" for t, c in zip(TIMES_H, conc))
(HERE / "profile.csv").write_text(csv)

nca_args = ["nca.run", "--csv", "profile.csv", "--param", "route=extravascular",
            "--param", "options.units=" + json.dumps(UNITS)]
nca = subprocess.run([CLI, *nca_args], check=True, capture_output=True, text=True, cwd=HERE)
subject = json.loads(nca.stdout)["result"]["subjects"][0]["outcome"]["ok"]

params = {p["name"]: {"value": p["value"]["value"], "unit": p.get("unit", "")}
          for p in subject["parameters"] if p["name"] in SHOWN and "value" in p["value"]}
lz = next(c for c in subject["lambda_z_candidates"] if c["selected"])

specimen = {
    "about": "Synthetic profile. Generated by site/specimen/make_specimen.py; do not edit by hand.",
    "commands": ["caladrius-cli " + " ".join(simulate), "caladrius-cli " + " ".join(nca_args)],
    "dose": {"value": DOSE_MG, "unit": "mg"},
    "units": UNITS,
    "profile": [{"t": t, "c": c} for t, c in zip(TIMES_H, conc)],
    "lambdaZ": {k: lz[k] for k in ("lambda_z", "intercept", "time_first", "time_last", "n_points")},
    "params": {name: params[name] for name in SHOWN},
}
(HERE.parent / "src" / "specimen.json").write_text(json.dumps(specimen, indent=2, ensure_ascii=False) + "\n")
print(json.dumps(specimen["params"], indent=1, ensure_ascii=False))
